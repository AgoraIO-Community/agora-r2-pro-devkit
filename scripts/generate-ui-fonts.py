"""Generate native-resolution 4 bpp UI fonts from SHA256-pinned sources.

Source TTF/OTF files stay external;
the generated fonts use renamed MyBot families and retain upstream font terms.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def rows(values, width=12):
    return '\n'.join('    ' + ', '.join(values[i:i + width]) + ','
                     for i in range(0, len(values), width))


def subset(path, size, characters, symbol, min_height, min_baseline):
    from PIL import Image, ImageDraw, ImageFont
    font = ImageFont.truetype(str(path), size)
    missing = bytes(font.getmask('\u0378'))
    bitmap = []
    descriptors = ['    {0}, /* Reserved glyph ID. */']
    ascent = descent = 0
    for codepoint in characters:
        character = chr(codepoint)
        if codepoint != 0x20 and bytes(font.getmask(character)) == missing:
            raise ValueError('Missing glyph U+%04X in %s' % (codepoint, path.name))
        x0, y0, x1, y1 = font.getbbox(character, anchor='ls')
        width, height = x1 - x0, y1 - y0
        if height == 0:
            width = 0
        descriptors.append('    /* U+%04X */\n'
            '    { .bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, '
            '.ofs_x = %d, .ofs_y = %d },' %
            (codepoint, len(bitmap), round(font.getlength(character) * 16),
             width, height, x0, -y1))
        if width and height:
            image = Image.new('L', (width, height))
            ImageDraw.Draw(image).text((-x0, -y0), character, font=font, fill=255, anchor='ls')
            coverage = [(value * 15 + 127) // 255 for value in image.getdata()]
            if len(coverage) % 2:
                coverage.append(0)
            bitmap.extend((coverage[i] << 4) | coverage[i + 1]
                          for i in range(0, len(coverage), 2))
            ascent = max(ascent, -y0)
            descent = max(descent, y1)
    baseline = max(min_baseline, descent + 1)
    line_height = max(min_height, ascent + baseline + 1)
    name = symbol
    print('%s: %d px, %d glyphs, %d bitmap bytes, line=%d baseline=%d' %
          (name, size, len(characters), len(bitmap), line_height, baseline))
    return '''
static const uint8_t {name}_bitmap[] = {{
{bitmap}
}};
static const lv_font_fmt_txt_glyph_dsc_t {name}_glyphs[] = {{
{glyphs}
}};
static const uint16_t {name}_unicode[] = {{
{unicode}
}};
static const lv_font_fmt_txt_cmap_t {name}_cmaps[] = {{
    {{ .range_start = {start}, .range_length = {length}, .glyph_id_start = 1,
       .unicode_list = {name}_unicode, .list_length = {count},
       .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY }},
}};
static const lv_font_fmt_txt_dsc_t {name}_dsc = {{
    .glyph_bitmap = {name}_bitmap, .glyph_dsc = {name}_glyphs,
    .cmaps = {name}_cmaps, .cmap_num = 1, .bpp = 4,
}};
const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {line_height}, .base_line = {baseline},
    .subpx = LV_FONT_SUBPX_NONE, .underline_position = -2, .underline_thickness = 1,
    .dsc = &{name}_dsc,
}};
'''.format(name=name, bitmap=rows(['0x%02x' % b for b in bitmap]),
           glyphs='\n'.join(descriptors),
           unicode=rows(['0x%04x' % (c - characters[0]) for c in characters]),
           start=characters[0], length=characters[-1] - characters[0] + 1,
           count=len(characters), line_height=line_height, baseline=baseline)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font-dir', type=Path, default=ROOT / 'local/fonts')
    parser.add_argument('--check', action='store_true', help='Verify generated bytes without changing files')
    args = parser.parse_args()
    from PIL import __version__ as pillow_version, features
    metadata = json.loads((ROOT / 'components/mybot_ui/fonts/sources.json').read_text())
    if pillow_version != metadata['pillow_version'] or features.version('freetype2') != metadata['freetype_version']:
        parser.error('Use the recorded Pillow/FreeType versions for reproducible font output')
    for name, source in metadata['fonts'].items():
        if hashlib.sha256((args.font_dir / name).read_bytes()).hexdigest() != source['sha256']:
            parser.error('Font source SHA256 mismatch: ' + name)
    header = ('/* Generated by scripts/generate-ui-fonts.py; Pillow %s, FreeType %s; 4 bpp. */\n'
              '#include "lvgl.h"\n' % (pillow_version, features.version('freetype2')))
    terminal = ('/* SPDX-License-Identifier: Bitstream-Vera */\n'
                '/* Renamed MyBot Terminal subsets of DejaVu Sans Mono Bold.\n'
                ' * Copyright (c) 2003 by Bitstream, Inc. All Rights Reserved.\n'
                ' * DejaVu changes are in public domain. See TERMINAL_FONT_LICENSE.txt.\n'
                ' * Input SHA256: %s\n */\n' % metadata['fonts']['DejaVuSansMono-Bold.ttf']['sha256'])
    terminal += header
    terminal += subset(args.font_dir / 'DejaVuSansMono-Bold.ttf', 18, list(range(32, 127)),
                       'mybot_terminal_font_18', 24, 6)
    terminal += subset(args.font_dir / 'DejaVuSansMono-Bold.ttf', 20, sorted(map(ord, '</>')),
                       'mybot_terminal_font_20', 26, 6)
    outputs = {ROOT / 'components/mybot_ui/fonts/generated/pixel_fonts.c': terminal}
    text = ('/* SPDX-License-Identifier: OFL-1.1 */\n'
            '/* Renamed MyBot UI Sans subset of Source Han Sans SC Normal.\n'
            ' * Copyright 2014-2021 Adobe (http://www.adobe.com/).\n'
            ' * See LVGL_VIEW_FONT_LICENSE.txt. Input SHA256: %s\n */\n' %
            metadata['fonts']['SourceHanSansSC-Normal.otf']['sha256'])
    text += header + subset(args.font_dir / 'SourceHanSansSC-Normal.otf', 40,
                            metadata['ui_codepoints'], 'mybot_lvgl_font_40', 52, 14)
    outputs[ROOT / 'components/mybot_ui/fonts/generated/lvgl_fonts.c'] = text
    pair = ('/* SPDX-License-Identifier: OFL-1.1 */\n'
            '/* Renamed MyBot Pair Code subset of Montserrat Medium.\n'
            ' * Copyright 2011 The Montserrat Project Authors.\n'
            ' * See the retained Montserrat OFL. Input SHA256: %s\n */\n' %
            metadata['fonts']['Montserrat-Medium.ttf']['sha256'])
    pair += header + subset(args.font_dir / 'Montserrat-Medium.ttf', 64,
                            list(range(32, 127)), 'mybot_pair_font_64', 70, 12)
    outputs[ROOT / 'components/mybot_ui/fonts/generated/pair_font.c'] = pair
    for path, content in outputs.items():
        if args.check:
            if path.read_text() != content:
                parser.error('Generated font differs: ' + str(path))
        else:
            path.write_text(content)
    if args.check:
        print('All generated font files match the pinned sources and generator.')


if __name__ == '__main__':
    main()
