"""Bind source, build configuration, dependencies, executable and ABI report."""

import argparse
from pathlib import Path

from build_metadata import build_inputs, digest, json_digest, read_json, verified_abi, write_json

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build-dir", type=Path, required=True)
    parser.add_argument("--prepare", action="store_true",
                        help="Snapshot inputs after configure, before compiling")
    args = parser.parse_args()
    build = args.build_dir.resolve()
    try:
        inputs = build_inputs(ROOT, build)
        if args.prepare:
            (build / "build-manifest.json").unlink(missing_ok=True)
            write_json(build / "build-inputs.json", inputs)
            source = build / "build_source_identity.c"
            contents = ('// SPDX-License-Identifier: Apache-2.0\n'
                        '// Generated by scripts/build-manifest.py --prepare.\n'
                        'const volatile char rv1126b_build_source_identity[] = '
                        '"MYBOT_RV1126B_SOURCE:' + inputs["source"]["sha256"] + '\\0"\n'
                        '    "MYBOT_RV1126B_INPUTS:' + json_digest(inputs) + '";\n')
            if not source.is_file() or source.read_text() != contents:
                source.write_text(contents)
            print("Prepared build inputs:", build / "build-inputs.json")
            return
        if inputs != read_json(build / "build-inputs.json"):
            raise ValueError("Inputs changed during build; reconfigure and rebuild")
        verified_abi(build, inputs["config"], inputs["source"]["sha256"], json_digest(inputs))
        manifest = {"schema": 1, "inputs": inputs,
                    "binary_sha256": digest(build / "mybot-rv1126b"),
                    "abi_report_sha256": digest(build / "abi-report.json")}
        write_json(build / "build-manifest.json", manifest)
        print("Build manifest:", build / "build-manifest.json")
    except (OSError, ValueError, KeyError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()
