"""Embed the authored Wi-Fi portal as deterministic, bounded C99 strings."""

import argparse
from pathlib import Path

TOKEN = b'@TOKEN@'
CHUNK_SIZE = 1024


def chunks(data):
    start = 0
    while start < len(data):
        end = min(start + CHUNK_SIZE, len(data))
        # The runtime substitutes tokens within each individual array entry.
        token = data.find(TOKEN, max(start, end - len(TOKEN) + 1))
        if token >= 0 and token < end < token + len(TOKEN):
            end = token
        yield data[start:end]
        start = end


def literal(data):
    escapes = {9: r'\t', 10: r'\n', 13: r'\r', 34: r'\"', 63: r'\?', 92: r'\\'}
    return '"' + ''.join(escapes.get(byte, chr(byte) if 32 <= byte < 127 else f'\\{byte:03o}')
                         for byte in data) + '"'


def generate(data):
    data.decode('utf-8')
    if b'\0' in data:
        raise ValueError('Portal input must not contain NUL bytes')
    entries = list(chunks(data)) or [b'']
    return ('/* SPDX-License-Identifier: Apache-2.0 */\n'
            '/* Generated by scripts/embed-wifi-portal.py; edit portal.html. */\n'
            '#ifndef RV1126B_WIFI_PORTAL_PAGE_H\n'
            '#define RV1126B_WIFI_PORTAL_PAGE_H\n\n'
            'static const char *const kPortalPage[] = {\n' +
            ''.join('    ' + literal(entry) + ',\n' for entry in entries) +
            '};\n\n#endif\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    try:
        content = generate(args.input.read_bytes())
        if not args.output.exists() or args.output.read_text(encoding='utf-8') != content:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(content, encoding='utf-8')
    except (OSError, UnicodeError, ValueError) as error:
        parser.error(str(error))


if __name__ == '__main__':
    main()
